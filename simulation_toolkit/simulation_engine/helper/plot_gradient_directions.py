def parse_bvec_data(data_string):
    """
    Parse multi-line string data into numpy array format
    Each line represents one coordinate (x, y, or z) with space-separated values
    """
    # Split the string into lines and strip whitespace
    lines = [line.strip() for line in data_string.strip().split('\n') if line.strip()]
    
    if len(lines) != 3:
        raise ValueError(f"Expected 3 lines (x, y, z coordinates), but got {len(lines)}")
    
    # Parse each line into coordinate arrays
    try:
        x_coords = [float(val) for val in lines[0].split()]
        y_coords = [float(val) for val in lines[1].split()]
        z_coords = [float(val) for val in lines[2].split()]
    except ValueError as e:
        raise ValueError(f"Error parsing coordinate values: {e}")
    
    # Verify all coordinate arrays have the same length
    if not (len(x_coords) == len(y_coords) == len(z_coords)):
        raise ValueError(f"Coordinate arrays must have same length. Got x:{len(x_coords)}, y:{len(y_coords)}, z:{len(z_coords)}")
    
    # Convert to numpy array for easier manipulation
    bvec_data = np.array([x_coords, y_coords, z_coords])
    
    print(f"Successfully parsed {len(x_coords)} direction vectors from bvec data")
    return bvec_data

def parse_bval_data(data_string):
    """
    Parse b-value data from a single line string with space-separated values
    """
    try:
        bval_array = np.array([float(val) for val in data_string.strip().split()])
        print(f"Successfully parsed {len(bval_array)} b-values from bval data")
        return bval_array
    except ValueError as e:
        raise ValueError(f"Error parsing b-values: {e}")

