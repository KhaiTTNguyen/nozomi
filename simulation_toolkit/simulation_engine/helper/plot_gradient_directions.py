def filter_vectors_by_bvalue(bvec_data, bval_data, bval_threshold=10.0):
    """
    Filter vectors based on b-values greater than threshold
    """
    if len(bval_data) != bvec_data.shape[1]:
        raise ValueError(f"Number of b-values ({len(bval_data)}) must match number of vectors ({bvec_data.shape[1]})")
    
    # Create mask for b-values greater than threshold
    bval_mask = bval_data > bval_threshold
    filtered_vectors = bvec_data[:, bval_mask]
    
    num_filtered_by_bval = np.sum(bval_mask)
    print(f"Filtered by b-value > {bval_threshold}: {num_filtered_by_bval} vectors kept out of {len(bval_data)}")
    
    return filtered_vectors, num_filtered_by_bval

def filter_and_normalize_vectors(bvec_data, threshold=0.001):
    """
    Filter out zero/near-zero vectors and normalize the remaining ones
    """
    # Calculate magnitude of each vector
    magnitudes = np.linalg.norm(bvec_data, axis=0)
    
    # Find non-zero directions
    non_zero_mask = magnitudes > threshold
    non_zero_vectors = bvec_data[:, non_zero_mask]
    
    # Normalize to unit length
    if non_zero_vectors.shape[1] > 0:
        normalized_vectors = non_zero_vectors / np.linalg.norm(non_zero_vectors, axis=0)
    else:
        normalized_vectors = non_zero_vectors
    
    num_non_zero = np.sum(non_zero_mask)
    print(f"Filtered by non-zero magnitude: {num_non_zero} vectors kept")
    
    return normalized_vectors, num_non_zero

def plot_dti_vectors(normalized_vectors, num_directions, num_bval_filtered):
    """
    Create 3D plot of DTI diffusion directions as vectors from origin
    """
    # Create figure and 3D axis
    fig = plt.figure(figsize=(12, 10))
    ax = fig.add_subplot(111, projection='3d')
    
    if normalized_vectors.shape[1] == 0:
        ax.text(0, 0, 0, "No vectors to display", fontsize=14, ha='center')
        ax.set_title('DTI Diffusion Direction Vectors\n(No vectors after filtering)', 
                    fontsize=14, fontweight='bold', pad=20)
        return fig, ax
    
    # Create origin points (all zeros)
    origin_x = np.zeros(normalized_vectors.shape[1])
    origin_y = np.zeros(normalized_vectors.shape[1])
    origin_z = np.zeros(normalized_vectors.shape[1])
    
    # Create a colormap for different vectors
    colors = plt.cm.viridis(np.linspace(0, 1, normalized_vectors.shape[1]))
    
    # Plot vectors using quiver
    ax.quiver(origin_x, origin_y, origin_z, 
              normalized_vectors[0], normalized_vectors[1], normalized_vectors[2],
              colors=colors, arrow_length_ratio=0.1, alpha=0.8, linewidth=1.5)
    
    # Alternative:Plot as lines from origin to each direction
    for i in range(normalized_vectors.shape[1]):
        ax.plot([0, normalized_vectors[0, i]], 
                [0, normalized_vectors[1, i]], 
                [0, normalized_vectors[2, i]], 
                color=colors[i], linewidth=2, alpha=0.7)
    
    # Set equal aspect ratio
    ax.set_xlabel('X', fontsize=12)
    ax.set_ylabel('Y', fontsize=12)
    ax.set_zlabel('Z', fontsize=12)
    
    # Set axis limits to show unit sphere range
    ax.set_xlim([-1.2, 1.2])
    ax.set_ylim([-1.2, 1.2])
    ax.set_zlim([-1.2, 1.2])
    
    # # Make the plot look proportional
    # ax.set_box_aspect([1,1,1])
    
    # Add title and labels
    ax.set_title(f'DTI Diffusion Direction Vectors\n(Filtered by b-value > 10: {num_bval_filtered} → {num_directions} final vectors)', 
                fontsize=14, fontweight='bold', pad=20)
    
    # Add grid for better visualization
    ax.grid(True, alpha=0.3)
    
    # Set a good viewing angle
    ax.view_init(elev=20, azim=45)
    
    return fig, ax

def main():
    """
    Main function to execute the DTI vector visualization with b-value filtering
    Users can modify the data_string_A and data_string_B variables below with their own data
    """
    # ===== USER INPUT SECTION =====
    # Replace these strings with your own DTI data
    # data_string_A: bvec data with 3 lines (x, y, z coordinates) with space-separated values
    # data_string_B: bval data with 1 line of b-values with space-separated values
    data_string_A = get_default_bvec_data()
    data_string_B = get_default_bval_data()
    
    # ===== PROCESSING SECTION =====
    print("Parsing DTI bvec data from string input...")
    try:
        bvec_data = parse_bvec_data(data_string_A)
    except ValueError as e:
        print(f"Error parsing bvec data: {e}")
        return
    
    print("Parsing DTI bval data from string input...")
    try:
        bval_data = parse_bval_data(data_string_B)
    except ValueError as e:
        print(f"Error parsing bval data: {e}")
        return
    
    print("Filtering vectors by b-value > 10...")
    try:
        filtered_by_bval, num_bval_filtered = filter_vectors_by_bvalue(bvec_data, bval_data)
    except ValueError as e:
        print(f"Error in b-value filtering: {e}")
        return
    
    print("Filtering and normalizing direction vectors...")
    normalized_vectors, num_final_directions = filter_and_normalize_vectors(filtered_by_bval)
    
    print(f"Final result: {num_final_directions} vectors will be plotted")
    print("Creating 3D vector visualization...")
    
    # Create the plot
    fig, ax = plot_dti_vectors(normalized_vectors, num_final_directions, num_bval_filtered)
    ax.view_init(elev=20, azim=0)
    # Show the plot
    plt.tight_layout()
    if not os.path.exists(OUTPUT_FOLDER_PATH):
        os.makedirs(OUTPUT_FOLDER_PATH)
    plt.savefig(OUTPUT_FOLDER_PATH+'/gradient_directions.png')

    
    # Optional: Save the plot
    # plt.savefig('dti_diffusion_vectors_filtered.png', dpi=300, bbox_inches='tight')
    
    print("Vector visualization complete!")

if __name__ == "__main__":
    main() 
